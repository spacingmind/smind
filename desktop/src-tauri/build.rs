#[path = "build_sidecar.rs"]
mod build_sidecar;

/// ensure_sidecar_placeholder: `tauri.macos.conf.json` and
/// `tauri.windows.conf.json` list `binaries/smind` as an `externalBin`,
/// and tauri-build refuses to build when `binaries/smind-<target-triple>`
/// (`.exe` on Windows) is missing -- which would break a plain
/// `cargo test`/`cargo clippy` on a machine that never staged the daemon
/// (`task desktop:mac` / `task desktop:win:daemon`). Debug builds get an
/// empty placeholder (the install path rejects an empty bundled binary
/// with a clear error); release builds never do, so a real bundle can't
/// silently ship without a daemon.
fn ensure_sidecar_placeholder() {
    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let profile = std::env::var("PROFILE").unwrap_or_default();
    let target = std::env::var("TARGET").expect("cargo sets TARGET for build scripts");
    let Some(path) = build_sidecar::sidecar_placeholder_name(&target_os, &profile, &target) else {
        // A release bundle must carry a real daemon: refuse a zero-length
        // sidecar left behind by an earlier debug build (a missing one is
        // already rejected by tauri-build).
        if profile == "release" {
            if let Some(real) = build_sidecar::sidecar_path(&target_os, &target) {
                if std::fs::metadata(&real).map(|m| m.len() == 0).unwrap_or(false) {
                    panic!("smind desktop: {} is an empty placeholder -- stage the daemon (task desktop:mac / task desktop:win:daemon) before a release build", real.display());
                }
            }
        }
        return;
    };
    if path.exists() {
        return;
    }
    std::fs::create_dir_all("binaries").expect("smind desktop: create binaries/");
    std::fs::write(&path, b"").expect("smind desktop: write sidecar placeholder");
}

fn main() {
    ensure_sidecar_placeholder();
    // AC5/AC6: the connection-picker/open-external commands get
    // autogenerated `allow-*`/`deny-*` permissions
    // (desktop/src-tauri/permissions/autogenerated/, gitignored, rebuilt
    // every build), referenced -- unprefixed, since they're app
    // commands, not a plugin's -- from capabilities/proxy.json.
    let attributes = tauri_build::Attributes::new().app_manifest(
        tauri_build::AppManifest::new().commands(&[
            "connections_list",
            "connections_add",
            "connections_add_relay",
            "connections_remove",
            "connections_select",
            "connections_get_current",
            "open_external",
            "app_quit",
            "app_menu_action",
            "editors_list",
            "open_in_editor",
            "daemon_status",
            "daemon_install",
            "daemon_update",
            "daemon_restart",
            "take_over_daemon",
            "connection_version",
            "window_ready",
            "window_set_theme",
            "app_update_check",
            "app_update_install",
        ]),
    );
    tauri_build::try_build(attributes).expect("smind desktop: tauri_build::try_build failed");
}
